def train_epoch(model, loader, optimizer, device, alpha: float, beta: float, gamma: float, huber_delta: float, y_mean: float, y_std: float):
    model.train()
    recon_crit = nn.MSELoss()
    # robust regression loss (Huber)
    reg_crit = nn.SmoothL1Loss(beta=huber_delta)

    total_loss = total_recon = total_fused = total_aux = 0.0
    y_true_all, y_pred_all = [], []

    for images, y, _codes in loader:
        images = images.to(device)
        y = y.to(device)

        # standardize target within fold (optional, but enabled here)
        y_norm = (y - y_mean) / (y_std + 1e-8)

        optimizer.zero_grad()
        recon, y_fused, snap_w, traj_w, y_snap, y_traj = model(images)

        # losses on normalized targets
        recon_loss = recon_crit(recon, images)
        fused_loss = reg_crit(y_fused, y_norm)

        snap_loss = reg_crit(y_snap, y_norm)
        traj_loss = reg_crit(y_traj, y_norm)
        aux_loss = 0.5 * (snap_loss + traj_loss)

        loss = alpha * recon_loss + beta * fused_loss + gamma * aux_loss
        loss.backward()
        optimizer.step()

        total_loss += float(loss.item())
        total_recon += float(recon_loss.item())
        total_fused += float(fused_loss.item())
        total_aux += float(aux_loss.item())

        # store predictions in original scale for reporting
        y_pred = (y_fused.detach().cpu().numpy() * (y_std + 1e-8)) + y_mean
        y_true = y.detach().cpu().numpy()
        y_true_all.append(y_true)
        y_pred_all.append(y_pred)

    y_true_all = np.concatenate(y_true_all) if y_true_all else np.array([])
    y_pred_all = np.concatenate(y_pred_all) if y_pred_all else np.array([])
    metrics = compute_regression_metrics(y_true_all, y_pred_all) if y_true_all.size else {"rmse": np.nan, "mae": np.nan, "r2": np.nan, "pearson_r": np.nan}

    n = max(1, len(loader))
    return (total_loss / n, total_recon / n, total_fused / n, total_aux / n, metrics)


def validate(model, loader, device, alpha: float, beta: float, gamma: float, huber_delta: float, y_mean: float, y_std: float):
    model.eval()
    recon_crit = nn.MSELoss()
    reg_crit = nn.SmoothL1Loss(beta=huber_delta)

    total_loss = total_recon = total_fused = total_aux = 0.0
    y_true_all, y_pred_all = [], []
    snap_all, traj_all = [], []

    with torch.no_grad():
        for images, y, _codes in loader:
            images = images.to(device)
            y = y.to(device)
            y_norm = (y - y_mean) / (y_std + 1e-8)

            recon, y_fused, snap_w, traj_w, y_snap, y_traj = model(images)

            recon_loss = recon_crit(recon, images)
            fused_loss = reg_crit(y_fused, y_norm)
            snap_loss = reg_crit(y_snap, y_norm)
            traj_loss = reg_crit(y_traj, y_norm)
            aux_loss = 0.5 * (snap_loss + traj_loss)

            loss = alpha * recon_loss + beta * fused_loss + gamma * aux_loss

            total_loss += float(loss.item())
            total_recon += float(recon_loss.item())
            total_fused += float(fused_loss.item())
            total_aux += float(aux_loss.item())

            y_pred = (y_fused.detach().cpu().numpy() * (y_std + 1e-8)) + y_mean
            y_true = y.detach().cpu().numpy()
            y_true_all.append(y_true)
            y_pred_all.append(y_pred)

            if snap_w is not None:
                snap_all.append(snap_w.detach().cpu().numpy())
            if traj_w is not None:
                traj_all.append(traj_w.detach().cpu().numpy())

    y_true_all = np.concatenate(y_true_all) if y_true_all else np.array([])
    y_pred_all = np.concatenate(y_pred_all) if y_pred_all else np.array([])
    metrics = compute_regression_metrics(y_true_all, y_pred_all) if y_true_all.size else {"rmse": np.nan, "mae": np.nan, "r2": np.nan, "pearson_r": np.nan}

    snap_arr = np.concatenate(snap_all) if len(snap_all) else None
    traj_arr = np.concatenate(traj_all) if len(traj_all) else None

    n = max(1, len(loader))
    return (total_loss / n, total_recon / n, total_fused / n, total_aux / n, metrics, snap_arr, traj_arr)


def collect_reports(model, loader, device, fold: int, split: str, y_mean: float, y_std: float):
    model.eval()
    rows = []

    with torch.no_grad():
        for images, y, codes in loader:
            images = images.to(device)
            y = y.to(device)

            recon, y_fused_norm, snap_w, traj_w, y_snap_norm, y_traj_norm = model(images)

            # invert normalization to report in original scale
            y_fused = (y_fused_norm.detach().cpu().numpy() * (y_std + 1e-8)) + y_mean
            y_snap = (y_snap_norm.detach().cpu().numpy() * (y_std + 1e-8)) + y_mean
            y_traj = (y_traj_norm.detach().cpu().numpy() * (y_std + 1e-8)) + y_mean

            y_true = y.detach().cpu().numpy()
            snap_np = snap_w.detach().cpu().numpy() if snap_w is not None else None
            traj_np = traj_w.detach().cpu().numpy() if traj_w is not None else None

            for i, code in enumerate(codes):
                r = {
                    "fold": fold,
                    "split": split,
                    "code": str(code),
                    "y_true": float(y_true[i]),
                    "y_pred_fused": float(y_fused[i]),
                    "y_pred_snap": float(y_snap[i]),
                    "y_pred_traj": float(y_traj[i]),
                }
                if snap_np is not None and snap_np.shape[1] >= 3:
                    r.update({
                        "snap_w_0h": float(snap_np[i, 0]),
                        "snap_w_6h": float(snap_np[i, 1]),
                        "snap_w_24h": float(snap_np[i, 2]),
                    })
                else:
                    r.update({"snap_w_0h": np.nan, "snap_w_6h": np.nan, "snap_w_24h": np.nan})

                if traj_np is not None and traj_np.shape[1] >= 3:
                    r.update({
                        "traj_w_0h": float(traj_np[i, 0]),
                        "traj_w_6h": float(traj_np[i, 1]),
                        "traj_w_24h": float(traj_np[i, 2]),
                    })
                else:
                    r.update({"traj_w_0h": np.nan, "traj_w_6h": np.nan, "traj_w_24h": np.nan})

                rows.append(r)

    return pd.DataFrame(rows)



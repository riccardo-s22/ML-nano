class ExcelImageDatasetRegression(Dataset):
    """
    Loads 3 timepoints per subject (0h, 6h, 24h) as a tensor: (T=3, C=1, H, W)
    and returns a float target y (ALSFRS-slope) plus the subject code.

    NOTE: This keeps the per-sample min-max normalization used in your original script.
    If absolute intensity is biologically meaningful, consider moving to dataset-level scaling.
    """
    def __init__(self, codes: List[str], targets: List[float], timepoint_dirs: List[str]):
        self.codes = [str(c) for c in codes]
        self.targets = [float(y) for y in targets]
        self.timepoint_dirs = timepoint_dirs

    def __len__(self) -> int:
        return len(self.codes)

    @staticmethod
    def load_excel_as_image(filepath: str) -> np.ndarray:
        wb = load_workbook(filepath, data_only=True)
        ws = wb.active

        data = []
        for row_idx, row in enumerate(ws.iter_rows(values_only=True)):
            if row_idx == 0:
                continue  # skip header row
            row_data = []
            for col_idx, cell in enumerate(row):
                if col_idx == 0:
                    continue  # skip emission label column
                if isinstance(cell, (int, float)) and cell is not None:
                    row_data.append(float(cell))
                else:
                    row_data.append(0.0)
            if len(row_data) > 0:
                data.append(row_data)

        img = np.array(data, dtype=np.float32)
        if img.size == 0:
            raise ValueError(f"No valid numeric data in {filepath}")

        # per-sample min-max normalization
        mn, mx = float(img.min()), float(img.max())
        if mx > mn:
            img = (img - mn) / (mx - mn)
        else:
            img = np.zeros_like(img, dtype=np.float32)

        return img

    def __getitem__(self, idx: int):
        code = self.codes[idx]
        y = self.targets[idx]

        tp_imgs = []
        for tp_dir in self.timepoint_dirs:
            fp = os.path.join(tp_dir, f"{code}.xlsx")
            arr = self.load_excel_as_image(fp)
            if arr.ndim == 2:
                arr = arr[np.newaxis, :, :]  # (1, H, W)
            tp_imgs.append(torch.tensor(arr, dtype=torch.float32))

        images = torch.stack(tp_imgs, dim=0)  # (T, C, H, W)
        target = torch.tensor(y, dtype=torch.float32)
        return images, target, code



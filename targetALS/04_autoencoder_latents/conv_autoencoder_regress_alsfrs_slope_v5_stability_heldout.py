class ConvEncoder(nn.Module):
    def __init__(self, in_channels: int, latent_dim: int):
        super().__init__()
        self.conv1 = nn.Sequential(
            nn.Conv2d(in_channels, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),
        )
        self.conv2 = nn.Sequential(
            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),
        )
        self.conv3 = nn.Sequential(
            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),
        )
        self.conv4 = nn.Sequential(
            nn.Conv2d(128, 256, kernel_size=3, padding=1),
            nn.BatchNorm2d(256),
            nn.ReLU(),
        )

        self.flatten_size = None
        self.fc = None
        self.latent_dim = latent_dim
        self.encoded_shape = None
        self.input_shape = None

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if self.input_shape is None:
            self.input_shape = (x.shape[2], x.shape[3])

        x = self.conv1(x)
        x = self.conv2(x)
        x = self.conv3(x)
        x = self.conv4(x)

        if self.encoded_shape is None:
            self.encoded_shape = (x.shape[1], x.shape[2], x.shape[3])

        if self.fc is None:
            self.flatten_size = x.shape[1] * x.shape[2] * x.shape[3]
            self.fc = nn.Linear(self.flatten_size, self.latent_dim).to(x.device)

        x = x.view(x.size(0), -1)
        z = self.fc(x)
        return z


class ConvDecoder(nn.Module):
    def __init__(self, latent_dim: int, out_channels: int, encoded_shape: Tuple[int, int, int], target_shape: Tuple[int, int]):
        super().__init__()
        enc_c, enc_h, enc_w = encoded_shape
        tgt_h, tgt_w = target_shape
        self.enc_c, self.enc_h, self.enc_w = enc_c, enc_h, enc_w
        self.tgt_h, self.tgt_w = tgt_h, tgt_w

        self.fc = nn.Linear(latent_dim, enc_c * enc_h * enc_w)

        self.deconv1 = nn.Sequential(
            nn.ConvTranspose2d(256, 128, kernel_size=3, stride=2, padding=1, output_padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
        )
        self.deconv2 = nn.Sequential(
            nn.ConvTranspose2d(128, 64, kernel_size=3, stride=2, padding=1, output_padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
        )
        self.deconv3 = nn.Sequential(
            nn.ConvTranspose2d(64, 32, kernel_size=3, stride=2, padding=1, output_padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
        )
        self.final_conv = nn.Conv2d(32, out_channels, kernel_size=3, padding=1)
        self.sigmoid = nn.Sigmoid()

    def forward(self, z: torch.Tensor) -> torch.Tensor:
        x = self.fc(z)
        x = x.view(x.size(0), self.enc_c, self.enc_h, self.enc_w)
        x = self.deconv1(x)
        x = self.deconv2(x)
        x = self.deconv3(x)
        x = self.final_conv(x)

        if x.shape[2] != self.tgt_h or x.shape[3] != self.tgt_w:
            x = torch.nn.functional.interpolate(
                x, size=(self.tgt_h, self.tgt_w), mode="bilinear", align_corners=False
            )

        return self.sigmoid(x)


class AttentionAggregation(nn.Module):
    """Order-invariant attention over timepoint latent vectors."""
    def __init__(self, latent_dim: int):
        super().__init__()
        self.attention_net = nn.Sequential(
            nn.Linear(latent_dim, 64),
            nn.Tanh(),
            nn.Linear(64, 1),
        )

    def forward(self, latent_vectors: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        # latent_vectors: (batch, T, latent_dim)
        scores = self.attention_net(latent_vectors).squeeze(-1)      # (batch, T)
        weights = torch.softmax(scores, dim=1)                       # (batch, T)
        z_agg = torch.sum(latent_vectors * weights.unsqueeze(-1), dim=1)  # (batch, latent_dim)
        return z_agg, weights


class TemporalEvolutionEncoder(nn.Module):
    """Order-aware GRU over time-ordered latent vectors, with optional step-attention."""
    def __init__(self, input_dim: int, hidden_dim: int = 64, use_step_attention: bool = True):
        super().__init__()
        self.rnn = nn.GRU(input_size=input_dim, hidden_size=hidden_dim, batch_first=True)
        self.use_step_attention = use_step_attention
        self.step_attn = nn.Linear(hidden_dim, 1) if use_step_attention else None

    def forward(self, latent_seq: torch.Tensor) -> Tuple[torch.Tensor, Optional[torch.Tensor]]:
        out, h = self.rnn(latent_seq)  # out: (batch, T, hidden_dim)
        if not self.use_step_attention:
            return h[-1], None
        scores = self.step_attn(out).squeeze(-1)     # (batch, T)
        weights = torch.softmax(scores, dim=1)       # (batch, T)
        embed = torch.sum(out * weights.unsqueeze(-1), dim=1)  # (batch, hidden_dim)
        return embed, weights


class RegressorHead(nn.Module):
    def __init__(self, in_dim: int, dropout: float = 0.3):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(in_dim, 128),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(128, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x).squeeze(-1)  # (batch,)


class FusionRegressor(nn.Module):
    def __init__(self, snap_dim: int, traj_dim: int, dropout: float = 0.3):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(snap_dim + traj_dim, 128),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(128, 1),
        )

    def forward(self, z_snap: torch.Tensor, z_traj: torch.Tensor) -> torch.Tensor:
        return self.net(torch.cat([z_snap, z_traj], dim=1)).squeeze(-1)


class ConvAutoencoderSnapshotsTrajectoryRegression(nn.Module):
    """
    Outputs:
        reconstructions: (batch, T, C, H, W)
        y_fused:         (batch,)
        snap_weights:    (batch, T)
        traj_weights:    (batch, T) or None
        y_snap:          (batch,)   auxiliary snapshot-only prediction
        y_traj:          (batch,)   auxiliary trajectory-only prediction
    """
    def __init__(self, in_channels: int, latent_dim: int, traj_hidden_dim: int = 64):
        super().__init__()
        self.encoder = ConvEncoder(in_channels, latent_dim)
        self.attention = AttentionAggregation(latent_dim)
        self.temporal = TemporalEvolutionEncoder(latent_dim, traj_hidden_dim, use_step_attention=True)

        self.decoder = None

        self.snap_head = RegressorHead(latent_dim)
        self.traj_head = RegressorHead(traj_hidden_dim)
        self.fusion_head = FusionRegressor(latent_dim, traj_hidden_dim)

        self.in_channels = in_channels
        self.latent_dim = latent_dim
        self.traj_hidden_dim = traj_hidden_dim

    def forward(self, timepoint_images: torch.Tensor):
        # timepoint_images: (batch, T, C, H, W)
        batch, T = timepoint_images.shape[0], timepoint_images.shape[1]

        latents = []
        for t in range(T):
            latents.append(self.encoder(timepoint_images[:, t]))  # (batch, latent_dim)
        latent_seq = torch.stack(latents, dim=1)  # (batch, T, latent_dim)

        # init decoder once shapes are known
        if self.decoder is None and self.encoder.encoded_shape is not None:
            self.decoder = ConvDecoder(
                self.latent_dim,
                self.in_channels,
                self.encoder.encoded_shape,
                self.encoder.input_shape,
            ).to(timepoint_images.device)

        # snapshot embedding
        z_snap, snap_w = self.attention(latent_seq)

        # trajectory embedding
        z_traj, traj_w = self.temporal(latent_seq)

        # reconstructions per timepoint
        recon = torch.stack([self.decoder(latent_seq[:, t]) for t in range(T)], dim=1)

        # predictions
        y_snap = self.snap_head(z_snap)
        y_traj = self.traj_head(z_traj)
        y_fused = self.fusion_head(z_snap, z_traj)

        return recon, y_fused, snap_w, traj_w, y_snap, y_traj


